dado = 10
print(f"Conteúdo da variável dado: {dado}")

dado += 1
print(f"Conteúdo da variável dado (depois (adição)): {dado}")

dado -= 1
print(f"Conteúdo da variável dado (depois (subtração)): {dado}")

dado *= 2
print(f"Conteúdo da variável dado (depois (multiplicação)): {dado}")

dado /= 2
print(f"Conteúdo da variável dado (depois (divisão)): {dado}")